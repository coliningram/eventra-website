#!/usr/bin/env node
/*
 * build-redirects.mjs: trailing-slash 301 generator (EVE-921).
 *
 * Cloudflare Workers static assets answer a folder address without its
 * trailing slash with a 307 to the slash address. That status code cannot be
 * configured. Since EVE-920 every canonical, sitemap entry and internal link
 * uses the slash address, so this script writes one static 301 line per page
 * folder into _redirects to make the move permanent for search engines.
 *
 * Behaviour:
 *  - Finds every folder under the repo root that holds an index.html. The root
 *    itself, hidden folders, and anything .assetsignore excludes are skipped.
 *  - Writes one line per folder, sorted, as `/path /path/ 301`.
 *  - Writes only inside the marked block at the end of _redirects and replaces
 *    that block on every run. Everything above the block is kept byte for byte.
 *  - A source path already used by a hand-written line above the block is left
 *    out of the block.
 *  - Idempotent: a second run leaves the file untouched.
 *  - No splat or placeholder rules: `/* /:splat/ 301` would also match the slash
 *    address and loop.
 *
 * Usage: node scripts/build-redirects.mjs [--check]
 *   --check  exit 1 if _redirects is out of date, without writing.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REDIRECTS = join(ROOT, '_redirects');
const BEGIN = '# BEGIN trailing-slash redirects (generated by scripts/build-redirects.mjs, do not edit by hand)';
const END = '# END trailing-slash redirects';
const CHECK = process.argv.includes('--check');

// .assetsignore uses gitignore-style globs. A pattern without a slash matches
// any single path segment; a pattern with a slash matches from the root.
function globToRegex(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') { re += '.*'; i++; }
    else if (c === '*') re += '[^/]*';
    else if (c === '?') re += '[^/]';
    else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp('^' + re + '$');
}

function loadIgnore() {
  const file = join(ROOT, '.assetsignore');
  if (!existsSync(file)) return [];
  return readFileSync(file, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((p) => {
      const anchored = p.includes('/');
      const clean = p.replace(/^\//, '').replace(/\/$/, '');
      return { anchored, re: globToRegex(clean) };
    });
}

const IGNORE = loadIgnore();

function isIgnored(rel) {
  const parts = rel.split('/');
  for (let i = 1; i <= parts.length; i++) {
    const prefix = parts.slice(0, i).join('/');
    const seg = parts[i - 1];
    for (const { anchored, re } of IGNORE) {
      if (anchored ? re.test(prefix) : re.test(seg)) return true;
    }
  }
  return false;
}

function findPageFolders(rel = '') {
  const out = [];
  const abs = join(ROOT, rel);
  for (const ent of readdirSync(abs, { withFileTypes: true })) {
    if (!ent.isDirectory() || ent.name.startsWith('.')) continue;
    const childRel = rel ? `${rel}/${ent.name}` : ent.name;
    if (isIgnored(childRel)) continue;
    const index = `${childRel}/index.html`;
    if (existsSync(join(ROOT, index)) && !isIgnored(index)) out.push(childRel);
    out.push(...findPageFolders(childRel));
  }
  return out;
}

const original = existsSync(REDIRECTS) ? readFileSync(REDIRECTS, 'utf8') : '';

// Split off the generated block. Everything before BEGIN is hand-written.
let head = original;
const at = original.indexOf(BEGIN);
if (at !== -1) {
  if (original.indexOf(END, at) === -1) {
    console.error('build-redirects: BEGIN marker without END marker in _redirects, aborting');
    process.exit(1);
  }
  head = original.slice(0, at);
}

const handSources = new Set(
  head
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => l.split(/\s+/)[0]),
);

const lines = findPageFolders()
  .map((p) => `/${p}`)
  .filter((src) => !handSources.has(src))
  .sort()
  .map((src) => `${src} ${src}/ 301`);

let prefix = head;
if (prefix && !prefix.endsWith('\n')) prefix += '\n';
const next = `${prefix}${BEGIN}\n${lines.join('\n')}${lines.length ? '\n' : ''}${END}\n`;

if (next === original) {
  console.log(`build-redirects: up to date (${lines.length} lines)`);
  process.exit(0);
}
if (CHECK) {
  console.error('build-redirects: _redirects is out of date');
  process.exit(1);
}
writeFileSync(REDIRECTS, next);
console.log(`build-redirects: wrote ${lines.length} lines`);
